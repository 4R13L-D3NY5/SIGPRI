export function getUNITEPCFacultades(sedeName: string): string[] {
  if (!UNITEPC_SEDES_DATA[sedeName]) return [];
  return Object.keys(UNITEPC_SEDES_DATA[sedeName]);
}

export function getUNITEPCCarreras(sedeName: string, facultadName: string): string[] {
  if (!UNITEPC_SEDES_DATA[sedeName] || !UNITEPC_SEDES_DATA[sedeName][facultadName]) return [];
  return UNITEPC_SEDES_DATA[sedeName][facultadName];
}
